-- 가입 경로는 birthDate를 UTC 자정(T00:00:00Z)으로 저장했고, 관리자 수정 경로는
-- KST 자정(T00:00:00+09:00)으로 저장했다. 두 값 모두 KST로 표시하면 같은 날짜로
-- 보여서 화면상으로는 문제가 없었지만, 저장된 순간(instant) 자체는 9시간 다르다.
-- 3단계에서 이름+생년월일로 학생을 매칭할 때 이 차이가 그대로 매칭 실패로 번진다.
-- (애플리케이션 쪽 수정은 src/lib/datetime.ts의 parseDateInputKst — 두 경로가 이제
-- 하나의 함수만 쓴다.)
--
-- 여기서는 기존 데이터를 KST 자정 기준으로 맞춘다. "birthDate::time = '00:00:00'"
-- 조건이 핵심이다 — UTC 자정으로 저장된 행은 시:분:초가 00:00:00이지만, 이미
-- KST 자정(9시간 당겨진 값)으로 저장된 행은 그렇지 않으므로 이 조건에 걸리지 않는다.
-- 조건 없이 전부 -9시간 하면 이미 맞는 행까지 또 밀려서 이중으로 어긋난다.
UPDATE "StudentProfile"
SET "birthDate" = "birthDate" - interval '9 hours'
WHERE "birthDate"::time = '00:00:00';
